"""Generate the proposed Upstream scripts for Trello #19 (inputs on PPP_Currency = USD).

Usage: python3 tools/propose_currency_usd.py <repo-root>

Rules (see proposed-changes/2026-11-09-upstream-currency-usd/README.md):
  R1  Calculations stay on PPP_Currency = "#".
  R2  Every RESULTLOOKUP of an upload input reads PPP_Currency = "USD".
  R3  Royalties steps 2-21 get MEMBERSET [d/PPP_Currency] = "#" (they had none).
  R4  Royalties cost loops (steps 14-17) iterate the USD input leaves and append to "#".
Central assumptions (GA_*, RR*, TL*, TA*) and calculated lines are not touched.
"""
import difflib
import json
import os
import re
import sys

# Upload inputs that now live on PPP_Currency = USD. Confirm AMT_46/AMT_90/AMT_97/SET* with Noel.
INPUTS = re.compile(r'^(AMT_(46|80|85|90|97|200|210|220|230)|UOM_\w+|SET\d+_\w+)$')
DAS = ["PPP_Upstream_Revenue", "PPP_Upstream_Royalties", "PPP_Upstream_Tax"]
COST_LOOPS = {14: ("CST05_15", "AMT_200"), 15: ("CST05_20", "AMT_210"),
              16: ("CST05_05", "AMT_220"), 17: ("CST05_10", "AMT_230")}


def fix_lookup(m):
    args = m.group(1)
    w = re.search(r'\[d/WPLn\]\s*=\s*"([^"]+)"', args)
    if not w or not INPUTS.match(w.group(1)):
        return m.group(0)
    if re.search(r'\[d/PPP_EntryNr\]\s*=\s*"UAP_GFP"', args):
        return m.group(0)  # gas flare penalty is calculated (Royalties step 13), stays on "#"
    if "[d/PPP_Currency]" in args:
        args = re.sub(r'\[d/PPP_Currency\]\s*=\s*"[^"]*"', '[d/PPP_Currency]="USD"', args)
    else:
        args = args.rstrip() + ', [d/PPP_Currency]="USD"'
    return f"RESULTLOOKUP({args})"


def transform(da, idx, script):
    out = []
    for line in script.splitlines():
        if line.lstrip().startswith("//"):
            out.append(line)
            continue
        out.append(re.sub(r'RESULTLOOKUP\(([^()]*)\)', fix_lookup, line))
    s = "\n".join(out)

    if da == "PPP_Upstream_Royalties" and 2 <= idx <= 21 and "MEMBERSET [d/PPP_Currency]" not in s:
        s = re.sub(r'(MEMBERSET \[d/Measures\][^\n]*\n)',
                   r'\1MEMBERSET [d/PPP_Currency] = "#"\n', s, count=1)

    if da == "PPP_Upstream_Royalties" and idx in COST_LOOPS:
        target, src = COST_LOOPS[idx]
        s = s.replace('MEMBERSET [d/PPP_Currency] = "#"\n', 'MEMBERSET [d/PPP_Currency] = ("#","USD")\n', 1)
        s = re.sub(
            r'IF \[d/PPP_EntryNr\] != "#" THEN\s*\n\s*DATA\.APPEND\(\[d/WPLn\] = "' + target +
            r'", \[d/PPP_EntryNr\] = "#"\) = RESULTLOOKUP\(\[d/WPLn\] = "' + src + r'"[^)]*\)',
            f'IF [d/PPP_EntryNr] != "#" AND [d/PPP_Currency] = "USD" THEN\n'
            f'\tDATA.APPEND([d/WPLn] = "{target}", [d/PPP_EntryNr] = "#", [d/PPP_Currency] = "#") = '
            f'RESULTLOOKUP([d/WPLn] = "{src}")', s)
    return s


def main(root):
    base = f"{root}/proposed-changes/2026-11-09-upstream-currency-usd"
    summary = []
    for da in DAS:
        d = json.load(open(f"{root}/sac-export/data-actions/{da}.json", encoding="utf-8"))
        for i, st in enumerate(d["steps"], 1):
            before = st.get("scriptContent")
            if not before:
                continue
            after = transform(da, i, before)
            if after.splitlines() == before.splitlines():
                continue
            name = re.sub(r"[^A-Za-z0-9]+", "_", st["name"]).strip("_")
            folder = f"{base}/{da}"
            os.makedirs(folder, exist_ok=True)
            with open(f"{folder}/step{i:02d}_{name}.advformula", "w", encoding="utf-8") as f:
                f.write(after.rstrip("\n") + "\n")
            diff = list(difflib.unified_diff(before.splitlines(), after.splitlines(),
                                             f"{da} step {i} (SAC now)", f"{da} step {i} (proposed)",
                                             lineterm="", n=1))
            changed = sum(1 for l in diff if l.startswith("+") and not l.startswith("+++"))
            summary.append((da, i, st["name"], changed, "\n".join(diff)))
    with open(f"{base}/DIFF.md", "w", encoding="utf-8") as f:
        f.write("# Script diff — Trello #19\n\nGenerated by `tools/propose_currency_usd.py` from the "
                "2026-11-09 snapshot.\n\n| Data action | Step | Lines changed |\n|---|---|---|\n")
        for da, i, n, c, _ in summary:
            f.write(f"| {da} | {i}. {n} | {c} |\n")
        for da, i, n, c, dtext in summary:
            f.write(f"\n## {da} — step {i}. {n}\n\n```diff\n{dtext}\n```\n")
    print(f"{len(summary)} steps changed, {sum(s[3] for s in summary)} lines")


if __name__ == "__main__":
    main(sys.argv[1])
